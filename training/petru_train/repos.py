"""Permissive GitHub corpus: verify licenses through the GitHub API, keep a catalog, clone shallowly."""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tomllib
from collections.abc import Callable
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path

PERMISSIVE = {"MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "0BSD", "CC0-1.0", "Unlicense"}
TRAINING_DIR = Path(__file__).resolve().parents[1]
SEED_FILE = TRAINING_DIR / "corpus" / "seed_repos.txt"
CATALOG_FILE = TRAINING_DIR / "corpus" / "repos.toml"
RAW_DIR = TRAINING_DIR / "corpus" / "raw"
MIN_FREE_GB = 30.0


@dataclass
class RepoInfo:
    url: str
    spdx: str | None
    ok: bool
    stars: int
    pushed_at: str
    default_branch: str
    language: str
    verified_at: str
    commit: str = ""
    name: str = field(default="")
    error: str | None = None

    def __post_init__(self) -> None:
        if not self.name:
            self.name = name_from_url(self.url)


def name_from_url(url: str) -> str:
    parts = url.rstrip("/").removesuffix(".git").split("/")
    return "__".join(parts[-2:])


def gh_api(path: str) -> dict:
    """`gh api <path>` as JSON; `gh` carries the user's authentication and rate limit."""
    proc = subprocess.run(["gh", "api", path], capture_output=True, text=True, encoding="utf-8")
    if proc.returncode != 0:
        raise RuntimeError(proc.stderr.strip() or f"gh api {path} failed")
    return json.loads(proc.stdout)


def verify_license(owner_repo: str, api: Callable[[str], dict] = gh_api) -> RepoInfo:
    today = date.today().isoformat()
    url = f"https://github.com/{owner_repo}"
    try:
        data = api(f"repos/{owner_repo}")
    except Exception as exc:
        return RepoInfo(url, None, False, 0, "", "", "", today, error=str(exc))
    license_info = data.get("license") or {}
    spdx = license_info.get("spdx_id") if isinstance(license_info, dict) else None
    return RepoInfo(
        url=str(data.get("html_url") or url),
        spdx=spdx,
        ok=spdx in PERMISSIVE,
        stars=int(data.get("stargazers_count") or 0),
        pushed_at=str(data.get("pushed_at") or ""),
        default_branch=str(data.get("default_branch") or "main"),
        language=str(data.get("language") or ""),
        verified_at=today,
    )


def write_catalog(infos: list[RepoInfo], path: Path) -> Path:
    lines = [
        "# Permissive GitHub repositories for training (generated by petru_train.repos; licenses verified).",
        "",
    ]
    for info in infos:
        if not info.ok:
            continue
        lines += [
            "[[repo]]",
            f'url = "{info.url}"',
            f'license = "{info.spdx}"',
            f'language = "{info.language}"',
            f"stars = {info.stars}",
            f'pushed_at = "{info.pushed_at}"',
            f'default_branch = "{info.default_branch}"',
            f'verified_at = "{info.verified_at}"',
            f'commit = "{info.commit}"',
            "",
        ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return path


def read_catalog(path: Path) -> list[RepoInfo]:
    with path.open("rb") as fh:
        data = tomllib.load(fh)
    return [
        RepoInfo(
            url=item["url"],
            spdx=item["license"],
            ok=True,
            stars=int(item.get("stars", 0)),
            pushed_at=str(item.get("pushed_at", "")),
            default_branch=str(item.get("default_branch", "main")),
            language=str(item.get("language", "")),
            verified_at=str(item.get("verified_at", "")),
            commit=str(item.get("commit", "")),
        )
        for item in data.get("repo", [])
    ]


def _free_gb(path: Path) -> float:
    target = path if path.exists() else path.parent
    return shutil.disk_usage(target).free / 1e9


def clone(
    info: RepoInfo, dest_root: Path, depth: int = 300, free_gb: Callable[[Path], float] = _free_gb
) -> Path:
    dest = dest_root / info.name
    if not (dest / ".git").exists():
        if free_gb(dest_root) < MIN_FREE_GB:
            raise RuntimeError(f"free disk below {MIN_FREE_GB:g} GB; not cloning {info.url}")
        dest_root.mkdir(parents=True, exist_ok=True)
        subprocess.run(
            [
                "git",
                "clone",
                "--depth",
                str(depth),
                "--single-branch",
                "--no-tags",
                "-q",
                info.url,
                str(dest),
            ],
            check=True,
            capture_output=True,
        )
    head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=str(dest), capture_output=True, text=True)
    info.commit = head.stdout.strip()
    return dest


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Verify licenses and clone the permissive GitHub corpus.")
    parser.add_argument("command", choices=["verify", "clone"])
    parser.add_argument("--seed", type=Path, default=SEED_FILE)
    parser.add_argument("--catalog", type=Path, default=CATALOG_FILE)
    parser.add_argument("--raw", type=Path, default=RAW_DIR)
    args = parser.parse_args(argv)
    if args.command == "verify":
        names = [ln.strip() for ln in args.seed.read_text(encoding="utf-8").splitlines()]
        infos = [verify_license(n) for n in names if n and not n.startswith("#")]
        for info in infos:
            print(f"{'OK  ' if info.ok else 'DROP'} {info.url} license={info.spdx} {info.error or ''}")
        write_catalog(infos, args.catalog)
        print(f"{sum(i.ok for i in infos)} of {len(infos)} repositories kept in {args.catalog}")
        return 0
    infos = read_catalog(args.catalog)
    for info in infos:
        try:
            dest = clone(info, args.raw)
            print(f"cloned {info.name} @ {info.commit[:12]} -> {dest}")
        except (RuntimeError, subprocess.CalledProcessError) as exc:
            print(f"FAILED {info.name}: {exc}")
    write_catalog(infos, args.catalog)
    return 0


if __name__ == "__main__":
    sys.exit(main())
